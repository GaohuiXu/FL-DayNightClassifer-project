#!/usr/bin/env python3
"""Generate the Cycle-02 alpha=0.2 stress-test YAMLs (2 cells).

The stage study found FLAME's CLEAN honest-rejection rate = 0.469 at
alpha=0.5 (drops ~half the honest clients every round, costing only
0.66 pp acc on GTSRB-43 because 26 admitted is still enough to train).
The natural follow-up: does this cost EXPLODE on more-non-IID data?

Mechanism: HDBSCAN needs a single cluster of size >= ceil(N/2)+1 = 26.
At alpha=0.2 the honest cloud is far more heterogeneous (label-skew is
sharper), so the benign cluster either (a) admits even fewer (clean
acc collapses) or (b) fails to form (admit-all fallback, no defense).
Either is a finding.

2 clean cells (no attack, 40r, alpha=0.2):
  - clean x FedAvg : convergence reference at alpha=0.2 (does the
    model still converge as well as alpha=0.5's 0.973?)
  - clean x FLAME  : the FPR + clean-accuracy cost at alpha=0.2

Outputs go to phase=alpha02, distinct from stages/ and ablation/.
"""
import os
OUT = os.path.dirname(os.path.abspath(__file__))

SHARED = """cycle: cycle_02
phase: alpha02
model-type: resnet18
pretrained-init: false
trainable-layers: full_ft
num-clients: 50
num-server-rounds: 40
fraction-train: 1.0
min-available-nodes: 50
min-train-nodes: 2
num-local-epochs: 3
learning-rate: 0.001
lr-schedule: cosine
lr-min: 0.0001
dirichlet-alpha: 0.2
malicious-client-ids:
num-malicious-nodes: 0
backdoor-target-label: 14
poison-fraction: 0.5
trigger-size: 4
trigger-value: 1.0
trigger-position: bottom-right
attack-start-round: 1
attack-end-round: 40
poison-data-regime: base
seed: 42
partition-seed: 42
topk-energy-k: 4096
checkpoint-rounds: ""
output-dir: '/mimer/NOBACKUP/groups/naiss2024-22-991/gaohui/fl_outputs/gtsrb'
wandb-enabled: true
wandb-project: cycle-02"""


def write(name, header, defense_type, group, tags):
    lines = [
        f"# {header}",
        "# Generated by _gen_alpha02.py -- do NOT edit by hand.",
        f"experiment-name: {name}",
        SHARED,
        "attack-type: pixel_backdoor",
        f"defense-type: {defense_type}",
        f"wandb-group: {group}",
        f"wandb-tags: {tags}",
    ]
    with open(os.path.join(OUT, f"{name}.yaml"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


count = 0
write("cycle02-alpha02-clean-fedavg",
      "Cycle 02 alpha=0.2 stress test: CLEAN x FedAvg, 40r. Convergence reference at alpha=0.2.",
      "none", "cycle02-alpha02-clean", "cycle02,alpha02,clean,fedavg")
count += 1
write("cycle02-alpha02-clean-flame",
      "Cycle 02 alpha=0.2 stress test: CLEAN x FLAME, 40r. FPR + clean-acc cost at alpha=0.2.",
      "flame", "cycle02-alpha02-clean", "cycle02,alpha02,clean,flame")
count += 1
print(f"wrote {count} YAMLs to {OUT}")
